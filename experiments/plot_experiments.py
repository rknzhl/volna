"""Paper figures from frozen final records; never fit or integrate a model.

Run from the repository root:
    .venv/bin/python experiments/plot_experiments.py

The TRAIN phase figure needs the preserved trusted local core-model pickle.
After its first export, --saved-arrays reproduces all figures without it.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import pickle
import sys

for name in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS", "MKL_NUM_THREADS",
             "VECLIB_MAXIMUM_THREADS", "NUMEXPR_NUM_THREADS"):
    os.environ[name] = "1"
os.environ.setdefault("MPLCONFIGDIR", "/private/tmp/takers_paper_experiments_mpl")

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import MaxNLocator
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
RESULTS = HERE / "data"
FIGURES = HERE / "figures"
PURPLE = "#76528B"
OLIVE = "#7E8651"
GRAY = "#7C7C7C"


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read_json(path):
    return json.loads(Path(path).read_text())


def source_entry(path):
    path = Path(path)
    try:
        location = str(path.relative_to(ROOT))
    except ValueError:
        location = str(path)
    return {"path": location, "sha256": sha256(path)}


def export_arrays(model_path):
    levels = (0, 1, 5, 10)
    runs = [read_json(RESULTS / f"noise{level:02d}.json") for level in levels]
    flow_records = read_json(RESULTS / "flow_verification.json")
    flows = {round(row["noise"] * 100): row for row in flow_records}
    provenance = runs[0]["fit"]["provenance"]
    for run in runs:
        assert run["fit"]["provenance"] == provenance
        assert run["transform_status"] == "transformed_conditionally"
        assert run["prediction_frozen_before_truth_evaluation"]
        assert run["train_phase_evaluation"]["absolute_determinant"] == 1
        assert run["fit"]["attempts"][-1]["diagnostics"]["dimension_selected"] == 3
    for filename, expected in provenance.items():
        actual = sha256(ROOT / "code/lag_ssa" / filename)
        if actual != expected:
            raise ValueError(f"Production source changed since the saved runs: {filename}")
    arrays = dict(
        noise_percent=np.asarray(levels),
        phase_mae_rad=np.asarray([r["test_phase_evaluation"]["mean_absolute_rad"] for r in runs]),
        sensor_nrmse_percent=100 * np.asarray([
            r["reconstruction_against_clean_total"]["train_channel_std_normalized_rmse"] for r in runs]),
        mssa_nrmse_percent=100 * np.asarray([
            r["preprocessed_against_clean_total"]["train_channel_std_normalized_rmse"] for r in runs]),
        full_turn_percent=100 * np.asarray([flows[level]["full_turn_relative"] for level in levels]),
        full_turn_max_percent=100 * np.asarray([flows[level]["full_turn_max"] for level in levels]),
        full_turn_limit_percent=np.asarray(5.0),
    )
    np.savez_compressed(HERE / "experiments_curved_noise_data.npz", **arrays)
    table = np.column_stack([arrays[key] for key in (
        "noise_percent", "phase_mae_rad", "sensor_nrmse_percent",
        "mssa_nrmse_percent", "full_turn_max_percent")])
    np.savetxt(HERE / "experiments_curved_noise_data.csv", table, delimiter=",",
               header="noise_percent,phase_mae_rad,sensor_nrmse_percent,mssa_nrmse_percent,full_turn_max_percent",
               comments="", fmt="%.12g")

    # Read only a trusted model generated by the current local experiment runner.
    with model_path.open("rb") as stream:
        model = pickle.load(stream)
    run = runs[0]
    assert model["status"] == "conditional_fields_first_model" and model["r"] == 3
    assert model["lag"] == run["fit"]["selected_lag"]
    estimated = np.asarray(model["phases"])
    trim = run["fit"]["preprocessing"]["boundary_trim_each_side"]
    raw_indices = np.arange(trim, trim + len(estimated))
    sys.path.insert(0, str(ROOT / "code/lag_ssa"))
    from fields_first_sensor_cases import generate_variant
    _, truth = generate_variant(run["case"], run["ntrain"], seed=run["seed"],
        noise=run["noise"], trend=run["trend"], train_count=run["ntrain"],
        phase_mode=run["phase_mode"], rate_profile=run["rate_profile"])
    match = run["train_phase_evaluation"]
    winding = np.asarray(match["winding_candidate"], dtype=int)
    origin = np.asarray(match["origins"])
    # Small explicit contraction avoids spurious macOS BLAS floating-point flags.
    target = np.einsum("ni,ji->nj", truth["theta"][raw_indices], winding, optimize=False) + origin
    residual = np.angle(np.exp(1j * (estimated - target)))
    if not np.isfinite(target).all() or not np.isfinite(residual).all():
        raise ValueError("Nonfinite saved-phase reference or residual")
    np.testing.assert_allclose(np.abs(residual).mean(), match["phase_mae_rad"], rtol=1e-11, atol=1e-13)
    np.testing.assert_allclose(np.abs(residual).max(), match["phase_max_abs_rad"], rtol=1e-11, atol=1e-13)
    np.savez_compressed(HERE / "experiments_train_phases_data.npz",
        raw_indices=raw_indices, window_indices=np.arange(len(estimated)),
        estimated_phase_rad=estimated, matched_reference_phase_rad=target,
        wrapped_residual_rad=residual, integer_gauge=winding, phase_origin_rad=origin,
        phase_display_count=np.asarray(40))

    records = [RESULTS / f"noise{level:02d}.json" for level in levels]
    records += [RESULTS / "flow_verification.json"]
    manifest = dict(
        scope="Saved final production outputs only; no fitting, persistence or flow integration performed by this script.",
        sources=[source_entry(path) for path in records],
        frozen_training_model=source_entry(model_path),
        generator_source=source_entry(ROOT / "code/lag_ssa/fields_first_sensor_cases.py"),
        production_source_hashes=provenance,
        plotting_script=source_entry(Path(__file__)),
        plotted_arrays=[source_entry(HERE / name) for name in (
            "experiments_curved_noise_data.npz", "experiments_train_phases_data.npz")],
        figure_outputs=[f"experiments/figures/{stem}.{suffix}"
            for stem in ("experiments_curved_noise", "experiments_train_phases", "extra_curved_noise_returns")
            for suffix in ("pdf",)],
        phase_figure=dict(role="supplementary", split="TRAIN", noise=0, phase_count=3,
            training_sample_count=run["ntrain"], retained_window_count=len(estimated),
            raw_window_start_first=int(raw_indices[0]), raw_window_start_last=int(raw_indices[-1]),
            reference="Generator phases transformed by the integer gauge and origins already saved in noise00.json.",
            integer_gauge=winding.tolist(), phase_origin_rad=origin.tolist(),
            gauge_refitted=False, train_phase_mae_rad=float(np.abs(residual).mean()),
            reference_panel_window_count=40, residual_panel_window_count=len(estimated)),
        noise_figure=dict(role="main", metrics=["phase MAE", "sensor NRMSE"],
            split="query", seed=31, training_sample_count=2400,
            query_input_sample_count=320, retained_query_snapshots=130,
            noise_definition="Noise standard deviation divided by clean TRAIN channel deviation; same orbit and standardized Gaussian realization across levels.",
            sensor_error_definition="RMSE against clean query readings after division by clean TRAIN channel deviations, expressed in percent.",
            control="Saved frozen MSSA conditioning output on the same inputs and retained query indices; not a separately tuned SSA/MSSA benchmark.",
            single_realization=True, line_segments="Guides between observed noise levels; no fitted response curve."),
        extra_noise_diagnostics=dict(role="supplementary", filename="extra_curved_noise_returns.pdf",
            full_turn="Saved independent checks: all 3 fields at 8 TRAIN starts, error divided by full prepared-window RMS.",
            flow_threshold_percent=5.0),
    )
    (HERE / "experiments_provenance.json").write_text(json.dumps(manifest, indent=2) + "\n")


def style_axes(ax):
    ax.spines[["top", "right"]].set_visible(False)
    ax.spines[["bottom", "left"]].set_color("#9A9A9A")
    ax.tick_params(width=.6, length=3, color="#9A9A9A")
    ax.set_axisbelow(True)
    ax.grid(axis="y", color="#E8E8E8", linewidth=.55)


def save(fig, stem):
    FIGURES.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIGURES / f"{stem}.pdf", facecolor="white",
                metadata={"Title": stem.replace("_", " "), "Creator": "plot_experiments.py"})
    plt.close(fig)


def plot_noise(include_returns=False):
    data = np.load(HERE / "experiments_curved_noise_data.npz")
    x = data["noise_percent"]
    if include_returns:
        fig, axs = plt.subplots(1, 3, figsize=(7.0, 2.72))
        fig.subplots_adjust(left=.105, right=.985, top=.82, bottom=.24, wspace=.47)
    else:
        fig, axs = plt.subplots(1, 2, figsize=(7.0, 3.0))
        fig.subplots_adjust(left=.115, right=.98, top=.83, bottom=.24, wspace=.35)
    for ax in axs:
        style_axes(ax)
        ax.tick_params(labelsize=10)
        ax.set_xticks(x)
        ax.set_xlim(-.5, 10.5)
        ax.yaxis.set_major_locator(MaxNLocator(4))
    axs[0].set_title("Phase error", loc="left", pad=12, fontsize=12)
    axs[0].plot(x, data["phase_mae_rad"], "o-", color=PURPLE, lw=1.4, ms=4)
    axs[0].set_ylabel("radians", fontsize=11)
    axs[0].set_ylim(0, .018)
    axs[1].set_title("Signal error", loc="left", pad=12, fontsize=12)
    axs[1].plot(x, data["sensor_nrmse_percent"], "o-", color=PURPLE, lw=1.4, ms=4, label="TorusFlow")
    axs[1].plot(x, data["mssa_nrmse_percent"], "s--", color=OLIVE, lw=1.2, ms=4, label="MSSA")
    axs[1].set_ylabel("error (%)", fontsize=11)
    axs[1].set_ylim(0, 3.5)
    axs[1].legend(frameon=False, fontsize=10, handlelength=1.6, loc="upper left", borderaxespad=0)
    if include_returns:
        axs[2].set_title("(c) Full-turn return", loc="left", pad=12)
        turns = data["full_turn_percent"].reshape(len(x), -1)
        # Offsets separate distinct starts; these are not confidence intervals.
        offset = np.linspace(-.12, .12, turns.shape[1])
        for xx, yy in zip(x, turns):
            axs[2].scatter(xx + offset, yy, s=8, color="#B8B8B8", alpha=.8, linewidths=0, zorder=2)
        axs[2].plot(x, data["full_turn_max_percent"], "o-", color=OLIVE, lw=1.4, ms=4, zorder=3)
        axs[2].axhline(5, color=GRAY, linestyle=(0, (4, 3)), lw=.9)
        axs[2].text(10.4, 5.12, "5% limit", ha="right", va="bottom", fontsize=8, color=GRAY)
        axs[2].set_ylabel("Window error (%)")
        axs[2].set_ylim(0, 5.8)
    fig.supxlabel("Noise level (%)", y=.06, fontsize=11)
    save(fig, "extra_curved_noise_returns" if include_returns else "experiments_curved_noise")


def plot_training_phases():
    data = np.load(HERE / "experiments_train_phases_data.npz")
    phi = np.mod(data["estimated_phase_rad"], 2 * np.pi)
    target = np.mod(data["matched_reference_phase_rad"], 2 * np.pi)
    residual = data["wrapped_residual_rad"]
    n = data["window_indices"]
    count = int(data["phase_display_count"])
    fig, axs = plt.subplots(3, 2, figsize=(7.0, 4.4), sharex="col")
    fig.subplots_adjust(left=.09, right=.98, top=.87, bottom=.12, wspace=.38, hspace=.23)
    for j in range(3):
        for ax in axs[j]:
            style_axes(ax)
        # Break reference lines at phase cuts instead of drawing false vertical paths.
        reference = target[:count, j].copy()
        reference[1:][np.abs(np.diff(reference)) > np.pi] = np.nan
        axs[j, 0].plot(n[:count], reference, color=GRAY, lw=1.15, label="Reference")
        axs[j, 0].scatter(n[:count], phi[:count, j], s=12, color=PURPLE, zorder=3, label="Estimate")
        axs[j, 0].set_yticks([0, np.pi, 2 * np.pi], ["0", r"$\pi$", r"$2\pi$"])
        axs[j, 0].set_ylim(-.25, 2 * np.pi + .25)
        axs[j, 0].set_xlim(-1, count)
        axs[j, 0].set_ylabel(rf"$\varphi_{j+1}$ (rad)")
        axs[j, 1].axhline(0, color="#CFCFCF", lw=.7)
        axs[j, 1].plot(n, residual[:, j], color=OLIVE, lw=.65)
        axs[j, 1].set_ylim(-.0145, .0145)
        axs[j, 1].set_yticks([-.01, 0, .01])
        axs[j, 1].set_xlim(0, n[-1])
        axs[j, 1].set_ylabel(rf"$\delta_{j+1}$ (rad)")
    axs[0, 0].set_title("(a) TRAIN phases", loc="left", pad=23)
    axs[0, 1].set_title("(b) Wrapped residuals", loc="left", pad=23)
    axs[0, 0].legend(frameon=False, ncol=2, fontsize=8.5, loc="lower left",
                     bbox_to_anchor=(0, 1.01), borderaxespad=0, handlelength=1.4,
                     columnspacing=1.4)
    for ax in axs[-1]:
        ax.set_xlabel("TRAIN window index")
    save(fig, "experiments_train_phases")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--saved-arrays", action="store_true",
                        help="Replot exported arrays without opening model pickles or generating reference phases.")
    parser.add_argument("--model", type=Path,
        default=Path("/private/tmp/takers_curved_noise_fix_20261022/noise00_candidate.pkl"))
    args = parser.parse_args()
    plt.rcParams.update({"font.family": "DejaVu Serif", "mathtext.fontset": "dejavuserif",
        "font.size": 9.5, "axes.titlesize": 10.5, "axes.labelsize": 9.5,
        "xtick.labelsize": 9, "ytick.labelsize": 9, "pdf.fonttype": 42,
        "ps.fonttype": 42, "axes.linewidth": .6, "savefig.pad_inches": .04})
    if not args.saved_arrays:
        export_arrays(args.model)
    plot_noise()
    plot_noise(include_returns=True)
    plot_training_phases()
    print("Saved the main two-panel noise figure and two supplementary figures.")


if __name__ == "__main__":
    main()
